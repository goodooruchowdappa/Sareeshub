// Joins all migrations into supabase/setup.sql so you can paste ONE file into the Supabase SQL editor.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const dir = "supabase/migrations";
const parts = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort()
  .map((f) => `-- ===== ${f} =====\n${readFileSync(`${dir}/${f}`, "utf8")}`);
writeFileSync("supabase/setup.sql", `-- Sarees Hub: complete database setup (generated by scripts/build-setup-sql.mjs).\n-- Run once in a NEW Supabase project: Dashboard → SQL Editor → paste → Run.\n\n${parts.join("\n\n")}`);
console.log("wrote supabase/setup.sql");
